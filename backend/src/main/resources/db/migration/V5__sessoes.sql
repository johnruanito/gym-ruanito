-- Sessões com refresh token rotativo.
-- O token em si NUNCA é gravado: só o hash SHA-256. Quem ler o banco (backup vazado,
-- acesso indevido) não consegue usar os tokens.

CREATE TABLE sessao (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT       NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    -- Todas as renovações de um mesmo login compartilham a família.
    -- Reuso de um token já trocado = sinal de roubo → a família inteira é revogada.
    familia     UUID         NOT NULL,
    token_hash  VARCHAR(64)  NOT NULL,
    criado_em   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expira_em   TIMESTAMPTZ  NOT NULL,
    revogado_em TIMESTAMPTZ,
    user_agent  VARCHAR(200),
    CONSTRAINT sessao_token_hash_uk UNIQUE (token_hash)
);

CREATE INDEX sessao_familia_idx       ON sessao (familia);
CREATE INDEX sessao_usuario_ativa_idx ON sessao (usuario_id) WHERE revogado_em IS NULL;
CREATE INDEX sessao_expira_idx        ON sessao (expira_em);
