-- Multi-academia (SaaS): cada registro de negócio pertence a uma academia.
-- Os dados existentes são atribuídos à academia 1, criada aqui.

CREATE TABLE academia (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(120) NOT NULL,
    ativa     BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ  NOT NULL DEFAULT now()
);

INSERT INTO academia (nome) VALUES ('Academia Principal');

-- ---------------------------------------------------------------------------
-- aluno: a matrícula deixa de ser chave primária global.
-- Duas academias podem ter a matrícula 20260001, então a PK passa a ser um id
-- sem significado e a matrícula fica única dentro de cada academia.
-- ---------------------------------------------------------------------------
ALTER TABLE acesso DROP CONSTRAINT acesso_aluno_matricula_fkey;
ALTER TABLE aluno  DROP CONSTRAINT aluno_pkey;

ALTER TABLE aluno ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE aluno ADD PRIMARY KEY (id);

ALTER TABLE aluno ADD COLUMN academia_id BIGINT NOT NULL DEFAULT 1 REFERENCES academia (id);
ALTER TABLE aluno ALTER COLUMN academia_id DROP DEFAULT;

-- CPF e RG: únicos por academia (o mesmo aluno pode treinar em duas academias clientes)
ALTER TABLE aluno DROP CONSTRAINT aluno_cpf_uk;
ALTER TABLE aluno DROP CONSTRAINT aluno_rg_uk;
ALTER TABLE aluno ADD CONSTRAINT aluno_matricula_uk UNIQUE (academia_id, matricula);
ALTER TABLE aluno ADD CONSTRAINT aluno_cpf_uk       UNIQUE (academia_id, cpf);
ALTER TABLE aluno ADD CONSTRAINT aluno_rg_uk        UNIQUE (academia_id, rg);

DROP INDEX aluno_situacao_idx;
CREATE INDEX aluno_situacao_idx ON aluno (academia_id, situacao);

-- ---------------------------------------------------------------------------
-- acesso: passa a referenciar aluno.id e ganha academia_id próprio
-- (permite filtrar relatórios por academia sem JOIN)
-- ---------------------------------------------------------------------------
ALTER TABLE acesso ADD COLUMN aluno_id    BIGINT;
ALTER TABLE acesso ADD COLUMN academia_id BIGINT;

UPDATE acesso a
   SET aluno_id = al.id, academia_id = al.academia_id
  FROM aluno al
 WHERE al.matricula = a.aluno_matricula;

ALTER TABLE acesso ALTER COLUMN aluno_id    SET NOT NULL;
ALTER TABLE acesso ALTER COLUMN academia_id SET NOT NULL;
ALTER TABLE acesso ADD CONSTRAINT acesso_aluno_fk    FOREIGN KEY (aluno_id)    REFERENCES aluno (id) ON DELETE RESTRICT;
ALTER TABLE acesso ADD CONSTRAINT acesso_academia_fk FOREIGN KEY (academia_id) REFERENCES academia (id);

ALTER TABLE acesso DROP COLUMN aluno_matricula; -- remove junto o índice antigo (aluno_matricula, entrada)

DROP INDEX acesso_entrada_idx;
DROP INDEX acesso_abertos_idx;
CREATE INDEX acesso_aluno_entrada_idx    ON acesso (aluno_id, entrada DESC);
CREATE INDEX acesso_academia_entrada_idx ON acesso (academia_id, entrada);
CREATE INDEX acesso_abertos_idx          ON acesso (academia_id, entrada) WHERE saida IS NULL;

