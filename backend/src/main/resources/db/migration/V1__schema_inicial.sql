-- Schema inicial da Academia 2.0 (PostgreSQL 16+).
-- Substitui o "drop-and-create" do JPA antigo, que apagava o banco a cada deploy.

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE estado (
    sigla VARCHAR(2)  PRIMARY KEY,
    nome  VARCHAR(30) NOT NULL
);

CREATE TABLE aluno (
    matricula        VARCHAR(10)  PRIMARY KEY,
    nome             VARCHAR(100) NOT NULL,
    sexo             VARCHAR(10)  NOT NULL CHECK (sexo IN ('MASCULINO', 'FEMININO')),
    rg               VARCHAR(20)  NOT NULL,
    cpf              VARCHAR(11)  NOT NULL CHECK (cpf ~ '^[0-9]{11}$'),
    data_nascimento  DATE         NOT NULL,
    situacao         VARCHAR(10)  NOT NULL CHECK (situacao IN ('ATIVO', 'INATIVO', 'PENDENTE')),
    email            VARCHAR(120),
    cep              VARCHAR(8)   NOT NULL CHECK (cep ~ '^[0-9]{8}$'),
    logradouro       VARCHAR(128) NOT NULL,
    numero           VARCHAR(10),
    complemento      VARCHAR(64),
    bairro           VARCHAR(128) NOT NULL,
    cidade           VARCHAR(64)  NOT NULL,
    estado_sigla     VARCHAR(2)   NOT NULL REFERENCES estado (sigla),
    celular_ddd      VARCHAR(2)   NOT NULL CHECK (celular_ddd ~ '^[0-9]{2}$'),
    celular_numero   VARCHAR(9)   NOT NULL CHECK (celular_numero ~ '^[0-9]{8,9}$'),
    criado_em        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    versao           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT aluno_cpf_uk UNIQUE (cpf),
    CONSTRAINT aluno_rg_uk  UNIQUE (rg)
);

-- Pesquisa por trecho do nome (LIKE '%x%') usa índice trigram em vez de full scan.
CREATE INDEX aluno_nome_trgm_idx ON aluno USING gin (lower(nome) gin_trgm_ops);
CREATE INDEX aluno_situacao_idx  ON aluno (situacao);

-- Contador atômico por ano para a matrícula (substitui SELECT MAX()+1, sujeito a corrida).
CREATE TABLE matricula_sequencia (
    ano    INTEGER PRIMARY KEY,
    ultimo INTEGER NOT NULL
);

CREATE TABLE acesso (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aluno_matricula VARCHAR(10) NOT NULL REFERENCES aluno (matricula) ON DELETE RESTRICT,
    entrada         TIMESTAMPTZ NOT NULL,
    saida           TIMESTAMPTZ,
    CONSTRAINT acesso_saida_apos_entrada CHECK (saida IS NULL OR saida >= entrada)
);

CREATE INDEX acesso_aluno_entrada_idx ON acesso (aluno_matricula, entrada DESC);
CREATE INDEX acesso_entrada_idx       ON acesso (entrada);
CREATE INDEX acesso_abertos_idx       ON acesso (entrada) WHERE saida IS NULL;

CREATE TABLE usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(50)  NOT NULL,
    senha_hash VARCHAR(100) NOT NULL,
    nome       VARCHAR(100) NOT NULL,
    papel      VARCHAR(20)  NOT NULL CHECK (papel IN ('ADMIN', 'RECEPCAO')),
    ativo      BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX usuario_username_uk ON usuario (lower(username));
